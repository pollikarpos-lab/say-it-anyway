// Налаштування середовища. Ключів тут немає і бути не може — цей файл
// віддається браузеру, його бачить кожен.
//
// На localhost лишається демо-режим: так можна працювати над інтерфейсом
// без ключів і без витрат, і так само ганяються наскрізні тести.
// На справжньому домені застосунок звертається до /api того ж сайту —
// це Worker із worker/index.js, у якого ключ є.
window.__SIA_CONFIG__ = (function () {
  var local = ['localhost', '127.0.0.1', '[::1]'].indexOf(location.hostname) !== -1;
  return {
    providerMode: local ? 'mock' : 'http',
    apiBaseUrl: '/api',
  };
})();
