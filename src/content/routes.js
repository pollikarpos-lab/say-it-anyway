export const ROUTES = [ROUTE_FEAR, ROUTE_ALONE];
export const DEFAULT_ROUTE_ID = ROUTE_FEAR.id;

export function getRoute(id) {
  return ROUTES.find(r => r.id === id) || ROUTES[0];
}

/** Маршрут, який варто запропонувати наступним. null — усі пройдені. */
export function nextRouteAfter(id, isComplete) {
  const rest = ROUTES.filter(r => r.id !== id && !isComplete(r.id));
  return rest[0] || null;
}
